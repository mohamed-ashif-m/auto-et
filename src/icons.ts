export function getCategoryIcon(name?: string | null): LucideIcon {
  if (name && ICON_COMPONENTS[name]) {
    return ICON_COMPONENTS[name]
  }

  return ICON_COMPONENTS.Tag
}

/**
 * Renders a category icon without assigning the component to a variable
 * during render (which would remount it on every render).
 */
export function renderCategoryIcon(
  name: string | null | undefined,
  size = 20,
  props?: Omit<LucideProps, 'size'>,
) {
  return createElement(getCategoryIcon(name), { size, ...props })
}
